#!/bin/bash

# BendCore Web - Build Script
# Builds backend and frontend for production

set -e

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

echo -e "${BLUE}BendCore Web - Build Script${NC}"
echo ""

# Timestamp
BUILD_TIME=$(date +"%Y-%m-%d %H:%M:%S")
echo -e "${YELLOW}Build started at $BUILD_TIME${NC}"
echo ""

# Backend build
echo -e "${YELLOW}Building backend...${NC}"
cd backend

echo "- Cleaning previous build..."
rm -rf dist

echo "- Installing dependencies..."
npm ci

echo "- Running TypeScript compiler..."
npm run build

echo "- Generating source maps..."
# Source maps are generated by tsconfig

BACKEND_SIZE=$(du -sh dist | cut -f1)
echo -e "${GREEN}✓ Backend built successfully (Size: $BACKEND_SIZE)${NC}"
cd ..

echo ""

# Frontend build
echo -e "${YELLOW}Building frontend...${NC}"
cd ui

echo "- Cleaning previous build..."
rm -rf dist

echo "- Installing dependencies..."
npm ci

echo "- Running Vite build..."
npm run build

FRONTEND_SIZE=$(du -sh dist | cut -f1)
echo -e "${GREEN}✓ Frontend built successfully (Size: $FRONTEND_SIZE)${NC}"
cd ..

echo ""

# Build verification
echo -e "${YELLOW}Verifying builds...${NC}"

if [ ! -d "backend/dist" ]; then
    echo -e "${RED}Error: Backend dist directory not found${NC}"
    exit 1
fi

if [ ! -d "ui/dist" ]; then
    echo -e "${RED}Error: Frontend dist directory not found${NC}"
    exit 1
fi

echo -e "${GREEN}✓ Build verification passed${NC}"
echo ""

# File count
BACKEND_FILES=$(find backend/dist -type f | wc -l)
FRONTEND_FILES=$(find ui/dist -type f | wc -l)

echo "Build Summary:"
echo "- Backend files: $BACKEND_FILES"
echo "- Frontend files: $FRONTEND_FILES"
echo "- Backend size: $BACKEND_SIZE"
echo "- Frontend size: $FRONTEND_SIZE"
echo ""

# Optional: Create archives
read -p "Create build archives? (y/n) " -n 1 -r
echo
if [[ $REPLY =~ ^[Yy]$ ]]; then
    echo "Creating archives..."

    tar -czf bendcore-backend-$(date +%Y%m%d-%H%M%S).tar.gz backend/dist
    tar -czf bendcore-frontend-$(date +%Y%m%d-%H%M%S).tar.gz ui/dist

    echo -e "${GREEN}✓ Archives created${NC}"
fi

echo ""
echo -e "${GREEN}Build completed successfully!${NC}"
echo ""
echo "Next steps:"
echo "1. Run tests: make test"
echo "2. Start Docker: docker-compose up"
echo "3. Deploy: make deploy-docker"
echo ""
